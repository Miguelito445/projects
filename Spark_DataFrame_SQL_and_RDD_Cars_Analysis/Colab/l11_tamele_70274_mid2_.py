"""Step 8 — Joined views for your id_20"""

from pyspark.sql.functions import col

joined = (
    execution.alias("e")
    .join(person.alias("p"), col("e.id_person") == col("p.id"))
    .join(dept.alias("d"), col("e.id_dept") == col("d.id"))
    .join(position.alias("pos"), col("e.id_position") == col("pos.id"))
    .join(action.alias("a"), col("e.id_execution") == col("a.id"))
    .select(
        col("e.id_20"),
        col("e.time"),
        col("e.cost"),
        col("e.payment"),
        col("p.name"),
        col("d.dept"),
        col("pos.position"),
        col("a.action")
    )
)

joined_id20 = joined.filter(col("id_20") == id_20)

joined_id20.show(5)

"""Step 8 — Joined views for your id_20"""

from pyspark.sql.functions import mean, stddev

count_obs = joined_id20.count()

stats = joined_id20.agg(
    mean("time").alias("mean_time"),
    stddev("time").alias("std_time"),
    mean("cost").alias("mean_cost"),
    stddev("cost").alias("std_cost"),
    mean("payment").alias("mean_payment"),
    stddev("payment").alias("std_payment")
)

print("Number of observations:", count_obs)
stats.show()