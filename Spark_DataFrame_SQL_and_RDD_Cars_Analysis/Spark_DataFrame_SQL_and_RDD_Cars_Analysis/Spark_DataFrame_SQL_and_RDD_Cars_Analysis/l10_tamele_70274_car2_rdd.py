"""# Exercise 3a (DF)
We compute mean, median, and standard deviation for MPG, Horsepower, and Weight.
We group by Origin and round results to two decimals.

"""

from pyspark.sql import functions as F

stats_df_Tamele70274 = (
    df_Tamele70274.groupBy("Origin")
    .agg(
        F.round(F.mean("MPG"),2).alias("mean_mpg"),
        F.round(F.expr("percentile(MPG, 0.5)"),2).alias("median_mpg"),
        F.round(F.stddev("MPG"),2).alias("std_mpg"),
        F.round(F.mean("Weight"),2).alias("mean_weight"),
        F.round(F.expr("percentile(Weight, 0.5)"),2).alias("median_weight"),
        F.round(F.stddev("Weight"),2).alias("std_weight"),
        F.count("*").alias("car_count")
    )
)

stats_df_Tamele70274.show(truncate=False)

"""# Exercise 3b (SQL)
We compute the same statistics using SQL functions.

"""

query_stats_sql_Tamele70274 = """
SELECT Origin,
       ROUND(AVG(MPG),2) AS mean_mpg,
       ROUND(percentile(MPG,0.5),2) AS median_mpg,
       ROUND(stddev(MPG),2) AS std_mpg,
       ROUND(AVG(Weight),2) AS mean_weight,
       ROUND(percentile(Weight,0.5),2) AS median_weight,
       ROUND(stddev(Weight),2) AS std_weight,
       COUNT(*) AS car_count
FROM cars
GROUP BY Origin
"""
spark_Tamele70274.sql(query_stats_sql_Tamele70274).show(truncate=False)

